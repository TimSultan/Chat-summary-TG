QUESTS: Final[tuple[Quest, ...]] = tuple(
    Quest(*row) for row in _DATA
) + tuple(Quest(*row) for row in _REAL_DATA)
PAINT_QUESTS: Final = tuple(quest for quest in QUESTS if quest.kind == "paint")
REAL_QUESTS: Final = tuple(quest for quest in QUESTS if quest.kind == "real")
QUEST_COUNT: Final = len(QUESTS)
PAINT_COUNT: Final = len(PAINT_QUESTS)
REAL_COUNT: Final = len(REAL_QUESTS)
_BY_CODE: Final = {quest.code: quest for quest in QUESTS}
DIFFICULTY_COUNTS: Final = {
    level: sum(1 for quest in PAINT_QUESTS if quest.difficulty == level)
    for level in DIFFICULTIES
}
TOOL_COUNTS: Final = {
    tool: sum(1 for quest in PAINT_QUESTS if quest.tool == tool) for tool in TOOLS
}


def normalise_code(code: str) -> str:
    """Fold a quest code to its canonical form.

    Codes used hyphens until it turned out Telegram's own hashtag parser stops at one --
    `#quest-nmm` was never one tag, it was the tag `#quest` followed by the plain text
    `-nmm`, so it neither highlighted nor grouped in search. Underscores are what Telegram
    accepts inside a tag, so that is what the codes are now.

    Folding here rather than migrating the stored data means every hyphenated code already
    written down -- a live assignment, a cooldown stamp, a hashtag somebody posted last
    week -- still resolves to the quest it always meant.
    """
    return str(code or "").strip().lower().replace("-", "_")


def find_quest(code: str) -> Quest | None:
    """The quest for this code, or None -- the code may be untrusted chat input."""
    return _BY_CODE.get(normalise_code(code))


def quests_by_difficulty(level: int) -> tuple[Quest, ...]:
    """Painting challenges at exactly this difficulty, in catalogue order.

    Paint only: this is what the daily assignment and its rerolls draw from, and a real
    quest is never dealt out -- it is taken from a list.
    """
    return tuple(quest for quest in PAINT_QUESTS if quest.difficulty == level)


def _validate_catalogue() -> None:
    """Fail immediately if a future catalogue edit violates its public contract.

    This runs at import, so a bad edit to the table above breaks the bot on startup
    rather than at midnight when somebody is handed a quest with no title.
    """
    assert PAINT_COUNT == 60
    assert REAL_COUNT >= 5
    assert len({quest.code for quest in QUESTS}) == QUEST_COUNT
    assert len({quest.title for quest in QUESTS}) == QUEST_COUNT
    assert all(quest.code and set(quest.code) <= _CODE_CHARS for quest in QUESTS)
    assert all(quest.difficulty in DIFFICULTIES for quest in QUESTS)
    assert all(quest.tool in TOOLS for quest in QUESTS)
    assert all(quest.kind in KINDS for quest in QUESTS)
    assert all(
        quest.title and quest.subject and quest.technique and quest.hint and quest.proof
        for quest in QUESTS
    )
    assert all(quest.cooldown_days >= 0 for quest in QUESTS)
    # A real quest is proved by something OTHER than a painted model, so leaving it on
    # the paint default means somebody forgot to say what to photograph.
    assert all(quest.proof != DEFAULT_PAINT_PROOF for quest in REAL_QUESTS)
    # Only paint challenges are dealt out, and a reroll walks UP the difficulties, so
    # every rung has to be reachable or a reroll at that level has nothing to offer.
    assert all(DIFFICULTY_COUNTS[level] >= 3 for level in DIFFICULTIES)
    assert sum(DIFFICULTY_COUNTS.values()) == PAINT_COUNT
    assert sum(TOOL_COUNTS.values()) == PAINT_COUNT
    assert all(hashtag(quest.code) == f"#quest_{quest.code}" for quest in QUESTS)
    # Telegram only treats letters, digits and underscores as part of a hashtag, so a
    # code with anything else in it would silently split the tag in half when posted.
    assert all("-" not in quest.code for quest in QUESTS)
    assert all(find_quest(quest.code.replace("_", "-")) is quest for quest in QUESTS)


_validate_catalogue()


