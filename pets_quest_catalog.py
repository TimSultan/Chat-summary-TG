"""The daily painting-quest catalogue: one technique per entry, immutable.

This module owns *data*, not game logic -- ``quests.py`` reads it to assign, describe
and reward a quest, but never edits it. Each :class:`Quest` names one real miniature-
painting technique and a SMALL, concrete thing that shows it off: one blade, one eye
pair, one shield boss. Deliberately never a whole miniature -- each of the three cards
should stay achievable inside its 24-hour window, not ask the player to paint an army.

``difficulty`` (1-5) is what ``quests.py`` prices the reward on -- see
``REWARDS_BY_DIFFICULTY`` there -- so it has to reflect genuine skill ceiling, not
enthusiasm: 1 is a first evening with a brush, 5 is weeks of deliberate practice (NMM,
realistic eyes at scale, sub-surface scattering, freehand lettering). Most techniques
are honestly in the 2-3 band, which is where most of the catalogue sits; only the
genuinely brutal ones earn a 5, and only real beginner wins earn a 1.

``tool`` records what the technique actually needs: airbrush-only effects (candy paint,
fades, pre-shading, stencils, masking, splatter, colour modulation, airbrush marbling)
are marked ``"airbrush"`` so a brush-only painter is never handed one; fine brushwork is
``"brush"``; anything doable either way is ``"any"``.

The hashtag a player posts under (``#quest_<code>``) is also how ``quests.py`` and
``pets_web.py`` recognise a submission -- see ``parse_hashtag`` in ``quests.py``, which
confirms the code against :func:`find_quest`. That is why ``code`` is constrained to
``[a-z0-9_]+``: it has to survive being typed by hand into a Telegram caption AND be one
hashtag when it gets there. Telegram ends a tag at the first character outside
letters/digits/underscore, so the earlier hyphenated codes posted as the tag ``#quest``
followed by loose text -- unclickable and ungrouped. :func:`normalise_code` folds the old
spelling onto the new one so nothing already written down was orphaned.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final


TOOLS: Final = ("brush", "airbrush", "any")
DIFFICULTIES: Final = (1, 2, 3, 4, 5)
_CODE_CHARS: Final = frozenset("abcdefghijklmnopqrstuvwxyz0123456789_")

HASHTAG_PREFIX: Final = "quest_"


KINDS: Final = ("paint", "real", "rune")
# What a paint challenge always asks for, so the 60 of them need not repeat it 60 times.
DEFAULT_PAINT_PROOF: Final = "фото покрашенной детали"


@dataclass(frozen=True, slots=True)
class Quest:
    """One immutable catalogue entry.

    TWO KINDS share this shape. A "paint" entry is a painting challenge -- a technique
    and one small thing to try it on -- and is what the daily assignment draws from. A
    "real" entry is a task away from the desk (Квесты в реале): tidy the bench, walk six
    kilometres, buy a loupe. They are listed rather than dealt out, and a player takes
    whichever they like, so nothing about them can leave an empty daily slot.

    The trailing fields all have defaults, so the 60 paint rows stay exactly as written
    and only the real ones spell out what makes them different:

      proof          what a moderator needs to SEE. A painting challenge is always a
                     photo of the painted thing; a real quest is the whole point of the
                     field ("фото рабочего места до и после").
      badge          a custom badge awarded on acceptance, by name. "" for most.
      cooldown_days  0 means once ever -- you cannot buy the same loupe twice. A positive
                     number makes it repeatable that many days later, which is what turns
                     tidying the bench into a fortnightly habit rather than a one-off.
    """

    code: str
    title: str
    subject: str
    technique: str
    difficulty: int
    tool: str
    hint: str
    kind: str = "paint"
    proof: str = DEFAULT_PAINT_PROOF
    badge: str = ""
    cooldown_days: int = 0


def hashtag(code: str) -> str:
    """The exact caption tag a player posts under for this quest's code."""
    return f"#{HASHTAG_PREFIX}{code}"


def _row_to_quest(row: tuple) -> "Quest":
    """Build one Quest, canonicalising its code on the way in.

    A row may be typed with hyphens -- they read naturally and half the catalogue was
    written that way -- but the stored code is always underscored, because the code IS the
    hashtag and Telegram ends a tag at the first hyphen (see normalise_code). Doing it here
    rather than demanding a particular spelling in the data means adding a quest never
    needs the author to remember this, and a typo in either direction still works.
    """
    return Quest(normalise_code(row[0]), *row[1:])


def normalise_code(code: str) -> str:
    """Fold a quest code to its canonical form.

    Codes used hyphens until it turned out Telegram's own hashtag parser stops at one --
    `#quest-nmm` was never one tag, it was the tag `#quest` followed by the plain text
    `-nmm`, so it neither highlighted nor grouped in search. Underscores are what Telegram
    accepts inside a tag, so that is what the codes are now.

    Folding here rather than migrating the stored data means every hyphenated code already
    written down -- a live assignment, a cooldown stamp, a hashtag somebody posted last
    week -- still resolves to the quest it always meant.
    """
    return str(code or "").strip().lower().replace("-", "_")


