_CODE_CHARS: Final = frozenset("abcdefghijklmnopqrstuvwxyz0123456789_")

HASHTAG_PREFIX: Final = "quest_"


KINDS: Final = ("paint", "real")
# What a paint challenge always asks for, so the 60 of them need not repeat it 60 times.
DEFAULT_PAINT_PROOF: Final = "фото покрашенной детали"


@dataclass(frozen=True, slots=True)
class Quest:
    """One immutable catalogue entry.

    TWO KINDS share this shape. A "paint" entry is a painting challenge -- a technique
    and one small thing to try it on -- and is what the daily assignment draws from. A
    "real" entry is a task away from the desk (Квесты в реале): tidy the bench, walk six
    kilometres, buy a loupe. They are listed rather than dealt out, and a player takes
    whichever they like, so nothing about them can leave an empty daily slot.

    The trailing fields all have defaults, so the 60 paint rows stay exactly as written
    and only the real ones spell out what makes them different:

      proof          what a moderator needs to SEE. A painting challenge is always a
                     photo of the painted thing; a real quest is the whole point of the
                     field ("фото рабочего места до и после").
      badge          a custom badge awarded on acceptance, by name. "" for most.
      cooldown_days  0 means once ever -- you cannot buy the same loupe twice. A positive
                     number makes it repeatable that many days later, which is what turns
                     tidying the bench into a fortnightly habit rather than a one-off.
    """

    code: str
    title: str
    subject: str
    technique: str
    difficulty: int
    tool: str
    hint: str
    kind: str = "paint"
    proof: str = DEFAULT_PAINT_PROOF
    badge: str = ""
    cooldown_days: int = 0


def hashtag(code: str) -> str:
    """The exact caption tag a player posts under for this quest's code."""
    return f"#{HASHTAG_PREFIX}{code}"


